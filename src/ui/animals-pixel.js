// SNES-style sprites for the Valley theme: 16x16, dark outline, a body
// color and one accent, drawn as crisp rects. Legend per sprite:
//   # outline   b body   a accent   w white   o eye (dark)   . empty

const OUTLINE = '#2b1d14';
const EYE = '#2b1d14';
const WHITE = '#f6f1e4';

function sprite(rows, body, accent) {
  if (rows.length !== 16 || rows.some((row) => row.length !== 16)) throw new Error('sprite rows must be 16 x 16');
  const colors = { '#': OUTLINE, b: body, a: accent, w: WHITE, o: EYE };
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const ch = row[x];
      if (ch in colors) {
        let run = 1;
        while (x + run < 16 && row[x + run] === ch) run++;
        rects.push(`<rect x="${x}" y="${y}" width="${run}" height="1" fill="${colors[ch]}"/>`);
        x += run;
      } else {
        x++;
      }
    }
  });
  return `<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}

